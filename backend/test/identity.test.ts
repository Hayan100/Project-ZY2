import assert from "node:assert/strict";
import test from "node:test";
import { randomBytes, randomUUID } from "node:crypto";
import { Pool } from "pg";
import { buildApi } from "../src/api.ts";
import { registerIdentity } from "../src/identity.ts";

test("verified login, replacement, activation and product access", { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const connectionString = process.env.TEST_DATABASE_URL;
  const owner = new Pool({ connectionString });
  const runtime = new Pool({ connectionString, options: "-c role=zy2_api" });
  const app = buildApi(async () => []);
  const origin = "http://localhost:3000";
  let message = "";
  registerIdentity(app, runtime, origin, randomBytes(32).toString("hex"), async (_to, _subject, text) => { message = text; });
  t.after(async () => { await app.close(); await runtime.end(); await owner.end(); });
  const email = randomUUID() + "@example.org";
  const password = randomBytes(20).toString("hex");
  let device = 1;
  const post = (path: string, payload: object, cookie = "") => app.inject({
    method: "POST", remoteAddress: "192.0.2." + device++, url: "/api/auth/" + path, headers: { origin, cookie }, payload,
  });
  const login = () => post("sign-in/email", { email, password });
  const get = (path: string, cookie: string) => app.inject({ url: "/api/v1/" + path, headers: { cookie } });
  const sessionCookie = (res: Awaited<ReturnType<typeof login>>) => {
    assert.equal(res.statusCode, 200, res.body);
    return res.cookies.map(c => c.name + "=" + c.value).join("; ");
  };
  assert.equal((await post("sign-up/email",{email,name:"x".repeat(201),password})).statusCode,400);
  assert.equal((await post("sign-up/email",{email,name:"line\nbreak",password})).statusCode,400);
  const crossSite = await app.inject({method:"POST",url:"/api/auth/sign-up/email",
    headers:{"sec-fetch-site":"cross-site"},payload:{email,name:"Student",password}});
  assert.equal(crossSite.statusCode,403);
  const signup = await post("sign-up/email", { email, name: "  Rene\u0301  ", password, role: "staff" });
  assert.equal(signup.statusCode, 200, signup.body);
  assert.equal((await owner.query('SELECT name FROM "user" WHERE email=$1',[email])).rows[0].name,"René");
  assert.equal((await login()).statusCode, 403);
  const link = new URL(message.trim().split("\n").at(-1)!);
  assert.ok((await app.inject(link.pathname + link.search)).statusCode < 400);
  const replay = await app.inject(link.pathname + link.search);
  assert.equal(replay.cookies.filter(c=>c.name.includes("session_token")).length,0);
  const peerLogin = await app.inject({method:"POST",url:"/api/auth/sign-in/email",remoteAddress:"192.0.2.88",
    headers:{origin,"x-client-ip":"198.51.100.17","x-forwarded-for":"198.51.100.17"},payload:{email,password}});
  assert.equal(peerLogin.statusCode,200,peerLogin.body);
  assert.equal((await owner.query('SELECT s."ipAddress" FROM session s JOIN "user" u ON u.id=s."userId" WHERE u.email=$1',[email])).rows[0].ipAddress,"192.0.2.88");
  const old = sessionCookie(await login());
  const simultaneous = await Promise.all([login(), login()]);
  const cookies = simultaneous.map(sessionCookie);
  const statuses = await Promise.all(cookies.map(c => get("me", c)));
  assert.deepEqual(statuses.map(r => r.statusCode).sort(), [200, 401]);
  const cookie = cookies[statuses.findIndex(r => r.statusCode === 200)];
  const me = (await get("me", cookie)).json();
  assert.equal(me.role, "student");
  assert.equal((await get("me", old)).statusCode, 401);
  const access = () => get("access/test-product", cookie);
  assert.equal((await access()).statusCode, 403);
  await owner.query("INSERT INTO staff_members VALUES ($1)", [me.id]);
  assert.equal((await get("me", cookie)).json().role, "staff");
  assert.equal((await access()).statusCode, 403);
  await owner.query("INSERT INTO enrollments(user_id,product_key,starts_at,ends_at) VALUES ($1,'test-product',now(),now()+interval '1 hour')", [me.id]);
  assert.equal((await access()).statusCode, 200);
  assert.equal((await get("access/other", cookie)).statusCode, 403);
  await owner.query("UPDATE enrollments SET revoked_at=now() WHERE user_id=$1", [me.id]);
  assert.equal((await access()).statusCode, 403);
  await owner.query("UPDATE enrollments SET revoked_at=null, starts_at=now()-interval '2 hours', ends_at=now() WHERE user_id=$1", [me.id]);
  assert.equal((await access()).statusCode, 403);
  await owner.query("UPDATE enrollments SET ends_at=now()+interval '1 day' WHERE user_id=$1", [me.id]);
  await owner.query("UPDATE enrollments SET starts_at=now()+interval '1 hour' WHERE user_id=$1", [me.id]);
  assert.equal((await access()).statusCode, 403);
  await owner.query("UPDATE enrollments SET starts_at=now() WHERE user_id=$1", [me.id]);
  await owner.query("INSERT INTO temporary_credentials VALUES ($1, now()+interval '1 day')", [me.id]);
  assert.equal((await get("me", cookie)).json().mustChangePassword, true);
  assert.equal((await access()).statusCode, 403);
  const newPassword = randomBytes(20).toString("hex");
  const changed = await post("change-password", {currentPassword: password, newPassword}, cookie);
  assert.equal(changed.statusCode, 200, changed.body);
  assert.equal((await get("me", cookie)).statusCode, 401);
  const fresh = sessionCookie(await post("sign-in/email", {email,password:newPassword}));
  assert.equal((await get("access/test-product", fresh)).statusCode, 200);
  const recoveryEmail=randomUUID()+"@example.org",recoveryPassword=randomBytes(18).toString("hex");
  const signup2=await post("sign-up/email",{name:"Recovery student",email:recoveryEmail,password:recoveryPassword});
  assert.equal(signup2.statusCode,200);
  const verify=new URL(message.trim().split("\n").at(-1)!);
  await app.inject(verify.pathname+verify.search);
  const recover=()=>app.inject({method:"POST",url:"/api/v1/staff/account-recovery",headers:{origin,cookie:fresh},payload:{
    id:recoveryId,student:signup2.json().user.id,evidence:"Verified enrollment reference",decision:"approved"}});
  const recoveryId=randomUUID();
  assert.equal((await recover()).statusCode,403);
  await owner.query("INSERT INTO recovery_staff VALUES($1)",[me.id]);
  assert.equal((await recover()).statusCode,200);
  const token=new URLSearchParams(new URL(message.trim().split("\n").at(-1)!).hash.slice(1)).get("token");
  assert.ok(token);
  const reset={token,newPassword:randomBytes(18).toString("hex")};
  assert.equal((await post("reset-password",reset)).statusCode,200);
  assert.ok((await post("reset-password",reset)).statusCode>=400);
  assert.equal((await post("sign-out", {}, fresh)).statusCode, 200);
  assert.equal((await get("me", fresh)).statusCode, 401);
});
