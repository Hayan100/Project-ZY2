import assert from "node:assert/strict";
import test from "node:test";
import {randomUUID} from "node:crypto";
import {Pool} from "pg";
import {buildApi} from "../src/api.ts";
import {registerRoutes} from "../src/router.ts";

test("pre-start onboarding, Ghazi allocation, private handoff, booking and expiry",{skip:!process.env.TEST_DATABASE_URL},async t=>{
  const connectionString=process.env.TEST_DATABASE_URL;
  const db=new Pool({connectionString}),runtime=new Pool({connectionString,options:"-c role=zy2_api"});
  const app=buildApi(async()=>[]);
  t.after(async()=>{await app.close();await runtime.end();await db.end();});
  const ops=randomUUID(),alice=randomUUID(),bob=randomUUID(),one=randomUUID(),two=randomUUID(),peer=randomUUID();
  for(const id of [ops,alice,bob,one,two,peer]){
    await db.query('INSERT INTO "user"(id,name,email,"emailVerified") VALUES($1,$1,$2,true)',[id,id+"@example.org"]);
    await db.query(`INSERT INTO session(id,"userId",token,"createdAt","updatedAt","expiresAt") VALUES($1,$1,$1,now(),now(),now()+interval '2 hours')`,[id]);
  }
  for(const id of [ops,one,two,peer]) await db.query("INSERT INTO staff_members VALUES($1)",[id]);
  await db.query("INSERT INTO welcome_admins VALUES($1)",[ops]);
  await db.query("INSERT INTO academic_staff VALUES($1)",[ops]);
  registerRoutes(app,runtime,async cookie=>cookie?{user:{id:cookie,emailVerified:true},session:{id:cookie}}:null,"http://localhost");
  const req=(method:"GET"|"POST"|"PUT",p:string,user:string,payload?:object)=>app.inject({method,url:"/api/v1/"+p,headers:{cookie:user},payload});
  const product=randomUUID(),id=randomUUID(),other=randomUUID(),staff="staff/onboarding",path="onboarding/"+id;
  for(const [e,u] of [[id,alice],[other,bob]]) await db.query(`INSERT INTO enrollments(id,user_id,product_key,starts_at,ends_at)
    VALUES($1,$2,$3,now()+interval '1 day',now()+interval '30 days')`,[e,u,product]);
  const put=(p:string,u:string,b:object)=>req("PUT",p,u,b);
  const get=(p:string,u=alice)=>req("GET",p,u);
  const post=(p:string,u:string,b:object)=>req("POST",p,u,b);
  assert.equal((await put(staff+"/products/"+product,peer,{route:"mentored",checkinDays:7})).statusCode,403);
  assert.equal((await put(staff+"/products/"+product,ops,{route:"mentored",checkinDays:7})).statusCode,200);
  assert.equal((await get("me/camp")).json().onboarding[0].preStart,true);
  assert.equal((await req("PUT","me/onboarding/profile",alice)).statusCode,200);
  assert.equal((await get("me/onboarding")).json().enrollments[0].profileConfirmed,true);
  assert.equal((await get(path,bob)).statusCode,404);
  const course=randomUUID(),lesson=randomUUID(),sibling=randomUUID();
  const l={id:lesson,title:"Orientation",type:"html_article",resourceId:randomUUID()};
  const outline={title:"Welcome",chapters:[{id:randomUUID(),title:"Start",lessons:[l,{...l,id:sibling,resourceId:randomUUID()}]}]};
  assert.equal((await post("staff/courses",ops,{id:course,productKey:product,outline})).statusCode,201);
  assert.equal((await post("staff/courses/"+course+"/publish",ops,{revision:1})).statusCode,200);
  const lessonUrl="courses/"+course+"/lessons/";
  assert.equal((await get(lessonUrl+lesson)).statusCode,404);
  assert.equal((await put(staff+"/cases/"+id+"/preparation",ops,{courseId:course,lessonId:lesson,selected:true,diagnostic:false})).statusCode,200);
  assert.equal((await get(lessonUrl+lesson)).statusCode,200);
  assert.equal((await get(lessonUrl+sibling)).statusCode,404);
  assert.equal((await get("courses/"+course)).statusCode,404);
  const questions=(await get(path)).json().intake.questions.map((q:{id:string})=>({...q,required:q.id==="goals"}));
  const scope="product:"+product;
  assert.equal((await put(staff+"/templates",ops,{scope,revision:0,questions})).statusCode,200);
  const form={scope,revision:1,version:0,submit:false,answers:[]};
  assert.equal((await put(path+"/intake",alice,form)).statusCode,200);
  assert.equal((await put(staff+"/templates",ops,{scope,revision:1,questions})).statusCode,200);
  assert.equal((await put(path+"/intake",alice,{...form,version:1,submit:true})).statusCode,422);
  assert.equal((await put(path+"/intake",alice,{...form,version:1,submit:true,answers:[{id:"goals",value:"Study regularly"}]})).statusCode,200);
  assert.equal((await get(path)).json().intake.revision,1);
  for(const [i,g] of [one,two].entries()) assert.equal((await put(staff+"/ghazis/"+g,ops,{
    capacity:1,priority:i+1,available:true,experience:"Tutoring",workingHours:"Weekdays 9–5 PKT",replyMinutes:60})).statusCode,200);
  const assign=(e:string,mentorId:string,version:number,overrideReason?:string)=>put(staff+"/cases/"+e+"/assignment",ops,{version,mentorId,overrideReason});
  assert.equal((await get(staff+"/allocation",ops)).json().suggestedMentorId,one);
  assert.equal((await assign(id,one,0)).statusCode,200);
  assert.equal((await assign(other,one,0)).statusCode,409);
  assert.equal((await assign(other,one,0,"Temporary cover for extra seat")).statusCode,200);
  assert.equal((await get("mentor/onboarding/"+id,one)).json().intake.answers[0].value,"Study regularly");
  assert.equal((await get("mentor/onboarding/"+id,peer)).statusCode,403);
  const planned={id:randomUUID(),title:"First-week reading",courseId:course,lessonId:sibling,
    startsAt:new Date(Date.now()+2*86400000).toISOString(),minutes:30};
  const planner="mentor/students/"+alice+"/planner/tasks/";
  const preview=await post(planner+"preview",one,planned);
  assert.equal(preview.statusCode,200,preview.body);
  assert.equal((await post(planner+"publish",one,{...planned,token:preview.json().token})).statusCode,200);
  assert.equal((await get(lessonUrl+sibling)).statusCode,404);
  const quiz=randomUUID(),option=randomUUID(),diag=randomUUID(),attempt=randomUUID();
  const questionsMCQ=[{id:randomUUID(),stem:"Pick one",options:[{id:option,text:"First"},{id:randomUUID(),text:"Second"}],
    correctOptionId:option,explanation:"Practice feedback"}];
  assert.equal((await post("staff/quizzes",ops,{id:quiz,quiz:{title:"Baseline",questions:questionsMCQ}})).statusCode,201);
  assert.equal((await post("staff/quizzes/"+quiz+"/publish",ops,{revision:1})).statusCode,200);
  const diagLesson={id:diag,title:"Optional baseline",type:"mcq_quiz",resourceId:quiz};
  const chapter=outline.chapters[0];
  assert.equal((await put("staff/courses/"+course,ops,{revision:1,outline:{...outline,chapters:[{...chapter,lessons:[...chapter.lessons,diagLesson]}]}})).statusCode,200);
  assert.equal((await post("staff/courses/"+course+"/publish",ops,{revision:2})).statusCode,200);
  assert.equal((await get(lessonUrl+lesson)).statusCode,404);
  assert.equal((await put(staff+"/cases/"+id+"/preparation",one,{courseId:course,lessonId:diag,diagnostic:true,selected:true})).statusCode,200);
  const practice=lessonUrl+diag+"/quizzes/"+quiz+"/attempts";
  assert.equal((await post(practice,alice,{id:attempt,diagnosticEnrollmentId:other})).statusCode,404);
  const started=await post(practice,alice,{id:attempt,diagnosticEnrollmentId:id});
  assert.equal(started.statusCode,200,started.body);
  assert.equal((await put(practice+"/"+attempt+"/answers/"+questionsMCQ[0].id,alice,{optionId:option})).statusCode,200);
  assert.equal((await post(practice+"/"+attempt+"/submit",alice,{})).statusCode,200);
  assert.equal((await get("mentor/onboarding/"+id,one)).json().diagnostics[0].correct,1);
  assert.equal((await get("mentor/onboarding",one)).statusCode,200);
  const soon=new Date(Date.now()+3600000).toISOString(),later=new Date(Date.now()+5*3600000).toISOString();
  const slot=randomUUID(),lateSlot=randomUUID();
  assert.equal((await post("mentoring/slots",one,{id:slot,mentorId:one,startsAt:soon})).statusCode,200);
  assert.equal((await post("mentoring/slots",one,{id:randomUUID(),mentorId:one,startsAt:new Date(Date.parse(soon)+22*60000).toISOString()})).statusCode,409);
  assert.equal((await post("mentoring/slots",one,{id:lateSlot,mentorId:one,startsAt:later})).statusCode,200);
  assert.equal((await get(path+"/slots")).json().slots.length,2);
  const book=(e:string,u:string,version:number,slotId:string)=>put("onboarding/"+e+"/booking",u,{version,mode:"video",slotId});
  const bookings=await Promise.all([book(id,alice,0,slot),book(other,bob,0,slot)]);
  assert.deepEqual(bookings.map(r=>r.statusCode).sort(),[200,409]);
  const win=bookings[0].statusCode===200?id:other,winner=win===id?alice:bob;
  assert.equal((await book(win,winner,1,lateSlot)).statusCode,409);
  assert.equal((await book(win,ops,1,lateSlot)).statusCode,200);
  assert.equal((await put("onboarding/"+win+"/booking",winner,{version:2,mode:"async_chat"})).statusCode,200);
  const text={id:randomUUID(),assignmentVersion:1,text:"Private hello"};
  assert.equal((await post(path+"/messages",alice,text)).statusCode,200);
  assert.equal((await post(path+"/messages",alice,text)).statusCode,200);
  assert.equal((await get(path+"/messages",ops)).statusCode,403);
  assert.equal((await get(path+"/messages",one)).json().messages.length,1);
  const follow={id:randomUUID(),strengths:"Persistence",priorities:"Reading",firstWeek:"Read daily",privateNote:"For mentor only",nextCheckin:later,status:"follow_up"};
  assert.equal((await post("mentor/onboarding/"+id+"/followups",one,follow)).statusCode,200);
  const hub=(await get(path)).json();
  assert.equal(hub.summary.strengths,follow.strengths);
  assert.equal(JSON.stringify(hub).includes(follow.privateNote),false);
  assert.equal((await put(staff+"/cases/"+id+"/welcome-cover",ops,{mentorId:two,until:later})).statusCode,200);
  assert.equal((await get(path+"/messages",two)).json().messages.length,0);
  assert.equal((await post(path+"/messages",two,{id:randomUUID(),assignmentVersion:1,text:"Welcome cover",welcome:true})).statusCode,200);
  assert.equal((await get(path+"/messages",two)).json().messages.length,1);
  assert.equal((await get(path+"/messages",one)).json().messages.length,1);
  assert.equal((await assign(id,two,1)).statusCode,200);
  assert.equal((await get(path+"/messages",one)).statusCode,403);
  assert.deepEqual((await get(path+"/messages",two)).json().messages,[]);
  assert.equal((await put(staff+"/cases/"+id+"/history-grants",ops,{reader:two,assignmentVersion:1,until:later})).statusCode,200);
  assert.equal((await get(path+"/messages",two)).json().messages.length,2);
  assert.equal((await put("mentor/students/"+alice+"/revision-budget",one,{minutes:15})).statusCode,403);
  assert.equal((await put("mentor/students/"+alice+"/revision-budget",two,{minutes:15})).statusCode,200);
  assert.equal((await put(staff+"/cases/"+id+"/term",ops,{endsAt:new Date(Date.now()-1000).toISOString()})).statusCode,200);
  assert.equal((await post(path+"/messages",alice,{...text,id:randomUUID(),assignmentVersion:2})).statusCode,403);
  assert.equal((await get(path+"/messages")).json().messages.length,2);
  assert.equal((await get(path+"/slots")).statusCode,403);
  assert.equal((await put("mentor/students/"+alice+"/revision-budget",two,{minutes:15})).statusCode,403);
  assert.equal((await get(lessonUrl+lesson)).statusCode,404);
  assert.ok((await get(path+"/access-log")).json().entries.some((e:{action:string})=>e.action==="read_chat"));
});
