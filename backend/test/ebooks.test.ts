import assert from "node:assert/strict";
import test from "node:test";
import {createServer} from "node:http";
import { randomUUID } from "node:crypto";
import { Pool } from "pg";
import { buildApi } from "../src/api.ts";
import { registerRoutes } from "../src/router.ts";

test("published ebooks share stable pages and reading state across authorized entry points",
  {skip:!process.env.TEST_DATABASE_URL},async t=>{
  const connectionString=process.env.TEST_DATABASE_URL;
  const owner=new Pool({connectionString});
  const runtime=new Pool({connectionString, options:"-c role=zy2_api"});
  const app=buildApi(async()=>[]);
  t.after(async()=>{await app.close(); await runtime.end(); await owner.end();});
  const staff=randomUUID(), student=randomUUID(), course=randomUUID(), lesson=randomUUID(), book=randomUUID();
  const courseKey=randomUUID(), libraryKey=randomUUID();
  for (const id of [staff,student]) {
    await owner.query('INSERT INTO "user"(id,name,email,"emailVerified") VALUES ($1,$1,$2,true)',[id,id+"@example.org"]);
    await owner.query(`INSERT INTO session(id,"userId",token,"createdAt","updatedAt","expiresAt")
      VALUES ($1,$1,$1,now(),now(),now()+interval '1 hour')`,[id]);
  }
  await owner.query("INSERT INTO staff_members VALUES ($1)",[staff]);
  await owner.query("INSERT INTO academic_staff VALUES ($1)",[staff]);
  const enroll=(key:string)=>owner.query(`INSERT INTO enrollments(user_id,product_key,starts_at,ends_at)
    VALUES ($1,$2,now(),now()+interval '1 hour')`,[student,key]);
  registerRoutes(app,runtime,async cookie=>cookie?{user:{id:cookie,emailVerified:true},session:{id:cookie}}:null,"http://localhost");
  const request=(method:"GET"|"POST"|"PUT",path:string,cookie:string,payload?:object)=>
    app.inject({method,url:"/api/v1/"+path,headers:{cookie},payload});
  const author="staff/ebooks", library="ebooks/"+book;
  const context="?courseId="+course+"&lessonId="+lesson;
  const page={id:randomUUID(),title:"Cell walls",blocks:[{type:"paragraph",text:"Cellulose provides structure."}]};
  const manuscript={title:"Biology",exam:"MDCAT",subject:"Botany",pages:[page]};
  const create={id:book,libraryProductKey:libraryKey,manuscript};
  assert.equal((await request("POST",author,student,create)).statusCode,403);
  assert.equal((await request("POST",author,staff,create)).statusCode,201);
  const publish=(revision:number)=>request("POST",author+"/"+book+"/publish",staff,{revision});
  const get=(path:string)=>request("GET",path,student);
  const lessonDoc={id:lesson,title:"Cells",type:"video",resourceId:randomUUID(),relatedResourceIds:[book]};
  const outline={title:"Intro",chapters:[{id:randomUUID(),title:"Botany",lessons:[lessonDoc]}]};
  assert.equal((await request("POST","staff/courses",staff,{id:course,productKey:courseKey,outline})).statusCode,201);
  const courseStaff="staff/courses/"+course;
  assert.equal((await request("POST",courseStaff+"/publish",staff,{revision:1})).statusCode,200);
  await enroll(courseKey);
  assert.equal((await get(library+context)).statusCode,404);
  assert.equal((await publish(1)).statusCode,200);
  const sample={id:randomUUID(),kind:"page",source:book,target:page.id,revision:1,title:"Sample page"};
  assert.equal((await request("POST","staff/samples",staff,sample)).statusCode,200);
  assert.deepEqual((await get("samples/"+sample.id)).json().item,page);
  assert.deepEqual((await get("ebooks")).json().ebooks,[]);
  assert.equal((await get(library)).statusCode,404);
  assert.equal((await get(library+"?courseId="+course)).statusCode,400);
  const pagePath=library+"/pages/"+page.id;
  assert.deepEqual((await get(pagePath+context)).json().page,page);
  const bookmark={kind:"page",source:book,target:page.id,course,lesson,saved:true};
  const annotation={id:randomUUID(),revision:1,version:0,start:0,end:9,body:"Review later"};
  const annotate=(b:typeof annotation)=>request("PUT",pagePath+"/annotations"+context,student,b);
  const annotations=async()=>(await get(library+"/annotations"+context)).json().annotations;
  assert.equal((await annotate(annotation)).statusCode,200);
  assert.equal((await annotate(annotation)).json().version,1);
  assert.equal((await annotate({...annotation,body:"stale edit"})).statusCode,409);
  assert.equal((await annotations())[0].resolved,true);
  assert.equal((await request("PUT","me/saved",student,bookmark)).statusCode,200);
  assert.equal((await get("me/saved")).json().items[0].href,"/api/v1/"+pagePath+context);
  assert.deepEqual((await request("GET","me/saved",staff)).json().items,[]);
  assert.equal((await request("PUT",pagePath+"/reading"+context,student,{revision:1,studied:true})).statusCode,200);
  await enroll(libraryKey);
  const assistant="me/study-assistant";
  assert.equal((await request("PUT","staff/ai-allowances/"+libraryKey,staff,{questions:1,days:30})).statusCode,200);
  let calls=0;
  const responder=createServer((_req,res)=>{calls++;res.setHeader("Content-Type","application/json");res.end('{"answer":"Review the linked page."}');});
  await new Promise<void>(resolve=>responder.listen(0,"127.0.0.1",resolve));
  const oldUrl=process.env.STUDY_ASSISTANT_URL;
  t.after(()=>{responder.close(); if(oldUrl===undefined) delete process.env.STUDY_ASSISTANT_URL; else process.env.STUDY_ASSISTANT_URL=oldUrl;});
  process.env.STUDY_ASSISTANT_URL="http://127.0.0.1:"+(responder.address() as {port:number}).port;
  const ask={id:randomUUID(),product:libraryKey,source:{book,page:page.id},question:"Explain this page"};
  for(let i=0;i<2;i++) assert.equal((await request("POST",assistant,student,ask)).json().href,"/api/v1/"+pagePath);
  assert.equal(calls,1);
  assert.equal((await request("POST",assistant,student,{...ask,id:randomUUID()})).statusCode,429);
  const home=async(q="")=>(await get("ebooks/home?q="+encodeURIComponent(q))).json();
  const shelf=(await home("BOTANY")).myBooks[0];
  assert.deepEqual([shelf.exam,shelf.subject],["MDCAT","Botany"]);
  assert.deepEqual([shelf.books[0].href,shelf.books[0].visited,shelf.books[0].studied],["/api/v1/"+library,1,1]);
  const filtered=await home("Physics");
  assert.deepEqual(filtered.myBooks,[]);
  assert.deepEqual(filtered.continueReading,{bookId:book,pageId:page.id,title:"Biology",href:"/api/v1/"+library});
  assert.deepEqual((await get("ebooks?q=botany")).json().ebooks,[{id:book,revision:1,title:"Biology",exam:"MDCAT",subject:"Botany",
    resumePageId:page.id,visited:1,studied:1,totalPages:1}]);
  assert.deepEqual((await get(library+"/search?q=CELLULOSE")).json().pages,[{id:page.id,title:page.title}]);
  assert.equal((await get(library)).json().pages[0].studied,true);
  assert.equal((await request("PUT",pagePath+"/reading",student,{revision:1})).json().studied,true);
  const replacement={...page,title:"New page",id:randomUUID()};
  const replace=(revision:number,pages:typeof page[])=>request("PUT",author+"/"+book,staff,{revision,manuscript:{...manuscript,pages}});
  assert.equal((await replace(1,[page,page])).statusCode,400);
  assert.equal((await replace(1,[replacement])).statusCode,200);
  assert.equal((await replace(1,[])).statusCode,409);
  assert.equal((await get(pagePath)).statusCode,200);
  assert.equal((await publish(2)).statusCode,200);
  assert.equal((await get("samples/"+sample.id)).statusCode,404);
  assert.equal((await get(pagePath)).statusCode,404);
  assert.equal((await request("PUT",pagePath+"/reading",student,{revision:1})).statusCode,409);
  assert.equal((await get(library)).json().resumePageId,null);
  assert.equal((await home()).continueReading,null);
  assert.equal((await annotations())[0].resolved,false);
  assert.equal((await annotate({...annotation,version:1,body:"Kept my original note"})).json().version,2);
  assert.equal((await replace(2,[replacement,page])).statusCode,200);
  assert.equal((await publish(3)).statusCode,200);
  assert.equal((await get(library)).json().resumePageId,page.id);
  const locked={...outline,chapters:[{...outline.chapters[0],lessons:[{...lessonDoc,releaseAt:"2099-01-01T00:00:00Z"}]}]};
  assert.equal((await request("PUT",courseStaff,staff,{revision:1,outline:locked})).statusCode,200);
  assert.equal((await request("POST",courseStaff+"/publish",staff,{revision:2})).statusCode,200);
  assert.equal((await get(pagePath+context)).statusCode,403);
  await owner.query("INSERT INTO content_security_staff VALUES ($1)",[staff]);
  const policy={graceSeconds:90,shortSeconds:60,longSeconds:120,shortMax:1,longMax:2,holdSeconds:30};
  assert.equal((await request("PUT","staff/content-access/policy/"+libraryKey,staff,policy)).statusCode,200);
  assert.equal((await request("POST","me/offline/ebook",student,{book})).statusCode,200);
  assert.equal((await get(pagePath)).statusCode,200);
  assert.equal((await get(library+"/pages/"+replacement.id)).statusCode,429);
  assert.equal((await request("POST","me/offline/ebook",student,{book})).statusCode,403);
  const pdfId=randomUUID(),pdfPage=randomUUID(),pdfAssetId=randomUUID();
  const pdfManuscript={...manuscript,pdfAssetId,pages:[{id:pdfPage,title:"Page 1",blocks:[]}]};
  assert.equal((await request("POST",author,staff,{id:pdfId,libraryProductKey:libraryKey,manuscript:pdfManuscript})).statusCode,201);
  assert.equal((await request("POST",author+"/"+pdfId+"/publish",staff,{revision:1})).statusCode,200);
  const inkPath="ebooks/"+pdfId+"/pages/"+pdfPage+"/ink",ink={id:randomUUID(),version:0,revision:1,points:[[0.1,0.2],[0.4,0.6]]};
  assert.equal((await request("PUT",inkPath,student,ink)).statusCode,200);
  assert.equal((await get("ebooks/"+pdfId+"/ink")).json().strokes[0].resolved,true);
  assert.equal((await request("PUT",author+"/"+pdfId,staff,{revision:1,manuscript:{...pdfManuscript,pdfAssetId:randomUUID()}})).statusCode,200);
  assert.equal((await request("POST",author+"/"+pdfId+"/publish",staff,{revision:2})).statusCode,200);
  assert.equal((await get("ebooks/"+pdfId+"/ink")).json().strokes[0].resolved,false);
  const pdfService=createServer((_req,res)=>{res.setHeader("Content-Type","application/json");
    res.end(JSON.stringify({url:"https://assets.example.test/page/1",expiresAt:new Date(Date.now()+30000).toISOString()}));});
  await new Promise<void>(resolve=>pdfService.listen(0,"127.0.0.1",resolve));
  const oldPdf=process.env.PDF_PAGE_URL;
  t.after(()=>{pdfService.close();if(oldPdf===undefined) delete process.env.PDF_PAGE_URL;else process.env.PDF_PAGE_URL=oldPdf;});
  process.env.PDF_PAGE_URL="http://127.0.0.1:"+(pdfService.address() as {port:number}).port;
  const ticketPath="ebooks/"+pdfId+"/pages/"+pdfPage+"/pdf-access";
  assert.equal((await request("POST",ticketPath,student)).statusCode,429);
  const alerts=(await request("GET","staff/content-access/alerts",staff)).json().alerts;
  assert.equal((await request("PUT","staff/content-access/alerts/"+alerts.find((x:{student:string})=>x.student===student).id,staff,{decision:"Verified reader"})).statusCode,200);
  assert.equal((await request("POST",ticketPath,student)).json().url,"https://assets.example.test/page/1");
  await owner.query("UPDATE enrollments SET revoked_at=now() WHERE user_id=$1",[student]);
  assert.deepEqual(await home(),{continueReading:null,myBooks:[]});
  assert.equal((await get(library+"/annotations"+context)).statusCode,404);
  assert.equal((await get("me/annotations/"+annotation.id+"/history")).json().versions.length,2);
  assert.equal((await get(pagePath)).statusCode,404);
  assert.equal((await get(pagePath+context)).statusCode,404);
  assert.equal((await get(library+"/search?q=cell")).statusCode,404);
});
