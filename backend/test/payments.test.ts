import {deliverNext,queueReminders,type Dispatch} from "../src/delivery.ts";
import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID, randomBytes } from "node:crypto";
import { Pool } from "pg";
import sharp from "sharp";
import { registerIdentity } from "../src/identity.ts";
import { buildApi } from "../src/api.ts";

test("checkout continuity and independent manual payment review", {skip:!process.env.TEST_DATABASE_URL}, async t => {
  const connectionString = process.env.TEST_DATABASE_URL;
  const owner = new Pool({connectionString});
  const runtime = new Pool({connectionString,options:"-c role=zy2_api"});
  const app = buildApi(async () => []);
  const origin = "http://localhost:3000";
  const mail = new Map<string,string>();
  process.env.GOOGLE_CLIENT_ID = "test-client";
  process.env.GOOGLE_CLIENT_SECRET = randomUUID();
  registerIdentity(app,runtime,origin,randomBytes(32).toString("hex"),async (to,_subject,text) => {mail.set(to,text);});
  t.after(async () => {await app.close(); await runtime.end(); await owner.end();});
  const batch = (await owner.query("INSERT INTO admission_batches(capacity) VALUES (1) RETURNING id")).rows[0].id;
  const offer = (await owner.query(`INSERT INTO payment_offers(product_key,amount_paisa,receiving_account,instructions,
    policy_version,policy_text,support_contact,review_hours,starts_at,ends_at,batch_id)
    VALUES ('biology',50000,'bank-1','Use bank transfer','v1','Sample policy','Sales',24,now(),now()+interval '30 days',$1) RETURNING id`,[batch])).rows[0].id;
  let device=1;
  const post = (url:string,payload:object,cookie="") => app.inject({method:"POST",url,payload,remoteAddress:"198.51.100."+device++,headers:{origin,cookie}});
  const get = (url:string,cookie="") => app.inject({url,headers:{cookie}});
  const route = "/api/v1/checkout/"+offer;
  const checkout = await get(route);
  assert.equal(checkout.json().next,"authenticate");
  const social = await post("/api/auth/sign-in/social",{provider:"google",checkoutOfferId:offer});
  assert.equal(social.statusCode,200,social.body);
  assert.equal(new URL(social.json().url).searchParams.get("redirect_uri"),origin+"/api/auth/callback/google");
  async function account() {
    const email = randomUUID()+"@example.org";
    const password = randomBytes(20).toString("hex");
    const signup = await post("/api/auth/sign-up/email",{name:"Account",email,password,checkoutOfferId:offer});
    assert.equal(signup.statusCode,200,signup.body);
    const link = new URL(mail.get(email)!.trim().split("\n").at(-1)!);
    const verified = await get(link.pathname+link.search);
    assert.equal(verified.headers.location,origin+route);
    const activated = verified.cookies.map(c=>c.name+"="+c.value).join("; ");
    assert.equal((await get(route,activated)).json().next,"confirm_invoice");
    const login = await post("/api/auth/sign-in/email",{email,password,checkoutOfferId:offer});
    assert.equal(login.statusCode,200,login.body);
    assert.equal(login.json().url,origin+route);
    return {id:login.json().user.id,cookie:login.cookies.map(c=>c.name+"="+c.value).join("; ")};
  }
  const student=await account(), sales=await account(), finance=await account(), other=await account();
  await owner.query("INSERT INTO staff_members VALUES ($1),($2)",[sales.id,finance.id]);
  await owner.query("INSERT INTO payment_permissions VALUES ($1,true,false),($2,false,true)",[sales.id,finance.id]);
  assert.equal((await get(route,student.cookie)).json().next,"confirm_invoice");
  const invoices="/api/v1/invoices", id=randomUUID();
  const terms={id,offerId:offer,studentId:student.id,policyVersion:"v1"};
  assert.equal((await post(invoices,terms)).statusCode,401);
  assert.equal((await post(invoices,terms,other.cookie)).statusCode,403);
  const issued=await post(invoices,terms,sales.cookie);
  assert.equal(issued.statusCode,200,issued.body);
  assert.equal(issued.json().status,"awaiting_proof");
  assert.equal((await get(route,student.cookie)).json().invoiceId,id);
  const item=invoices+"/"+id, access="/api/v1/access/biology";
  const image=(await sharp({create:{width:4,height:4,channels:3,background:"white"}}).png().toBuffer()).toString("base64");
  const upload=(revision:number,cookie:string) => post(item+"/proofs",{revision,image},cookie);
  assert.equal((await upload(1,sales.cookie)).statusCode,200);
  assert.equal((await get(item+"/proof",student.cookie)).headers["content-type"],"image/jpeg");
  assert.equal((await get(item+"/proof",other.cookie)).statusCode,404);
  assert.equal((await get(access,student.cookie)).statusCode,403);
  const check={revision:1,amountPaisa:50000,reference:"TX-"+randomUUID(),transferredAt:new Date().toISOString()};
  assert.equal((await post(item+"/verify",check,sales.cookie)).statusCode,403);
  await owner.query("UPDATE payment_permissions SET verifier=true WHERE staff_id=$1",[sales.id]);
  assert.equal((await post(item+"/verify",check,sales.cookie)).statusCode,403);
  const corrected=await post(item+"/correction",{revision:1,reason:"Please show the reference"},finance.cookie);
  assert.equal(corrected.statusCode,200,corrected.body);
  assert.equal((await upload(2,student.cookie)).statusCode,200);
  assert.equal((await post(item+"/verify",check,finance.cookie)).statusCode,409);
  check.revision=2;
  assert.equal((await post(item+"/verify",{...check,amountPaisa:1},finance.cookie)).statusCode,409);
  const second=randomUUID();
  assert.equal((await post(invoices,{id:second,offerId:offer,policyVersion:"v1"},other.cookie)).statusCode,200);
  const base=invoices+"/"+second;
  const schedule=[{amountPaisa:20000,dueAt:new Date(Date.now()-120000).toISOString()},{amountPaisa:30000,dueAt:new Date(Date.now()-60000).toISOString()}];
  assert.equal((await post(base+"/installments/request",{schedule},other.cookie)).statusCode,200);
  assert.equal((await post(base+"/installments/approve",{schedule},sales.cookie)).statusCode,403);
  await owner.query("UPDATE payment_permissions SET plan_approver=true WHERE staff_id=$1",[finance.id]);
  const approval=await post(base+"/installments/approve",{schedule},finance.cookie);
  assert.equal(approval.statusCode,200,approval.body);
  assert.equal((await get(access,other.cookie)).statusCode,403);
  assert.equal((await post(invoices+"/"+second+"/assign-sales",{staffId:sales.id},other.cookie)).statusCode,200);
  assert.equal((await post(invoices+"/"+second+"/proofs",{revision:1,image},sales.cookie)).statusCode,200);
  const early=new Date().toISOString();
  const verify=()=>post(item+"/verify",check,finance.cookie);
  for(const res of await Promise.all([verify(),verify()])) assert.equal(res.statusCode,200,res.body);
  assert.equal((await get(access,student.cookie)).statusCode,200);
  const secondCheck={...check,amountPaisa:20000,revision:1,reference:"OTHER-"+randomUUID()};
  const verifySecond=(payload:object)=>post(invoices+"/"+second+"/verify",payload,finance.cookie);
  const soldOut=(await owner.query("SELECT sold_out_at::text AS at FROM admission_batches WHERE id=$1",[batch])).rows[0].at;
  assert.equal((await verifySecond({...secondCheck,transferredAt:new Date(Date.parse(soldOut)+1).toISOString()})).statusCode,409);
  assert.equal((await verifySecond({...secondCheck,reference:check.reference,transferredAt:early})).statusCode,409);
  const lateReview=await verifySecond({...secondCheck,transferredAt:early});
  assert.equal(lateReview.statusCode,200,lateReview.body);
  assert.equal((await owner.query("SELECT extra_seat FROM payment_receipts WHERE invoice_id=$1",[second])).rows[0].extra_seat,true);
  assert.equal((await owner.query("SELECT occupied FROM admission_batches WHERE id=$1",[batch])).rows[0].occupied,2);
  assert.equal((await owner.query("SELECT count(*)::int AS n FROM enrollments WHERE user_id=$1",[student.id])).rows[0].n,1);
  assert.equal(lateReview.json().balance_paisa,30000);
  assert.equal((await get(access,other.cookie)).statusCode,200);
  assert.ok((await get("/api/v1/payments/overdue",finance.cookie)).json().some((i:{id:string})=>i.id===second));
  const delivery=new Pool({connectionString,options:"-c role=zy2_delivery"});
  t.after(()=>delivery.end());
  await queueReminders(delivery);
  const extended=await post(base+"/installments/extend",{part:2,dueAt:new Date(Date.now()+86400000).toISOString(),reason:"Agreed extension"},finance.cookie);
  assert.equal(extended.statusCode,200,extended.body);
  const previous=(await owner.query("SELECT * FROM enrollments WHERE user_id=$1",[other.id])).rows[0];
  assert.equal((await post(base+"/proofs",{revision:2,image},other.cookie)).statusCode,200);
  const finalPayment={...secondCheck,revision:2,amountPaisa:30000,reference:randomUUID(),transferredAt:new Date().toISOString()};
  for (const res of await Promise.all([verifySecond(finalPayment),verifySecond(finalPayment)])) {
    assert.equal(res.statusCode,200,res.body);
    assert.equal(res.json().status,"paid");
  }
  const receipts=(await get(base+"/receipts",other.cookie)).json();
  assert.deepEqual(receipts.map((r:{amount_paisa:number})=>r.amount_paisa),[20000,30000]);
  assert.deepEqual((await owner.query("SELECT * FROM enrollments WHERE user_id=$1",[other.id])).rows,[previous]);
  assert.equal((await owner.query("SELECT occupied FROM admission_batches WHERE id=$1",[batch])).rows[0].occupied,2);
  for (const learner of [student,other]) {
    const whatsapp=learner===student ? "+15555550100" : "+15555550101";
    const contact=await post("/api/v1/me/receipt-whatsapp",{whatsapp},learner.cookie);
    assert.equal(contact.statusCode,200,contact.body);
    assert.equal((await post("/api/v1/payments/verify-whatsapp",{whatsapp,studentId:learner.id},learner.cookie)).statusCode,403);
    assert.equal((await post("/api/v1/payments/verify-whatsapp",{whatsapp,studentId:learner.id},finance.cookie)).statusCode,200);
  }
  const delivered=new Set<string>();
  const fake:Dispatch=async notice=>{
    assert.ok(notice.destination);
    assert.equal(notice.kind,"receipt");
    const key=notice.receipt_id+":"+notice.channel;
    assert.ok(!delivered.has(key));
    delivered.add(key);
    return {complete:true};
  };
  await deliverNext(delivery,async()=>{throw new Error("transient failure");});
  await owner.query("UPDATE payment_messages SET next_attempt=now() WHERE attempts=1");
  while(await deliverNext(delivery,fake)) {}
  assert.equal(delivered.size,6);
  assert.equal((await owner.query("SELECT count(*)::int n FROM payment_messages WHERE accepted_at IS NULL")).rows[0].n,0);
});
